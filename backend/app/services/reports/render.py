"""Quality / compliance reports as JSON, HTML and PDF. All user text is HTML-escaped."""

from __future__ import annotations

from datetime import UTC, datetime
from html import escape
from typing import Any

SEV_COLOR = {
    "critical": "#b91c1c",
    "high": "#c2410c",
    "medium": "#a16207",
    "low": "#1d4ed8",
    "info": "#475569",
}


def report_html(
    *,
    title: str,
    document: str,
    kind: str,
    version: int,
    run: dict[str, Any],
    findings: list[dict[str, Any]],
    compliance: dict[str, Any] | None = None,
) -> str:
    stats = run.get("stats", {})
    scores = stats.get("scores") or {}
    dims = scores.get("dimensions", {})
    rows = []
    for f in findings:
        color = SEV_COLOR.get(f["severity"], "#475569")
        rows.append(
            f"<tr><td style='color:{color};font-weight:bold'>{escape(f['severity'].upper())}</td>"
            f"<td><b>{escape(f['message'])}</b><br/><i>{escape(f['location'] or '')}</i><br/>"
            f"{escape(f['explanation'])}<br/><span style='color:#166534'>Fix: {escape(f['recommendation'])}</span>"
            f"{'<br/><small>Status: ' + escape(f['status']) + '</small>' if f['status'] != 'open' else ''}"
            f"</td><td><small>{escape(f['code'])}</small></td></tr>"
        )
    dim_cells = "".join(f"<td><b>{escape(str(v))}</b><br/><small>{escape(k)}</small></td>" for k, v in dims.items())
    comp = ""
    if compliance:
        comp = (
            f"<h2>Compliance: {escape(compliance.get('standard', ''))}</h2>"
            f"<p><b>{escape(str(compliance.get('score')))}</b> / 100 — {escape(compliance.get('verdict', ''))}. "
            f"Hard rules passed {compliance.get('hard_pass', 0)}, failed {compliance.get('hard_fail', 0)}; "
            f"soft rules passed {compliance.get('soft_pass', 0)}, failed {compliance.get('soft_fail', 0)}; "
            f"not evaluated {compliance.get('not_evaluated', 0)}.</p>"
        )
    skipped = stats.get("not_evaluated") or []
    skipped_html = ""
    if skipped:
        items = "".join(
            f"<li>{escape(s.get('check') or s.get('rule', ''))}: {escape(s.get('reason', ''))}</li>" for s in skipped
        )
        skipped_html = f"<h3>Not evaluated</h3><ul>{items}</ul>"
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    return f"""<html><body style="font-family:sans-serif;font-size:10pt">
<h1>{escape(title)}</h1>
<p>Document: <b>{escape(document)}</b> ({escape(kind.upper())}, version {version})<br/>
Generated by AKSHARA on {now}. Engine {escape(str(run.get("engine_version", "")))}.</p>
{comp}
<h2>Quality score: {escape(str(scores.get("overall", "—")))} / 100</h2>
<table border="1" cellpadding="4"><tr>{dim_cells}</tr></table>
<h2>Findings ({len(findings)})</h2>
<table border="1" cellpadding="4" style="width:100%">{"".join(rows) or "<tr><td>No findings.</td></tr>"}</table>
{skipped_html}
<p><small>Scores: dimension = max(0, 100 - weighted findings); weights critical 25, high 10, medium 4,
low 1, info 0. Findings on inferred (PDF) structure count at reduced confidence.</small></p>
</body></html>"""
